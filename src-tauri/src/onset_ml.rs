/// Resolve the path of a model file inside the app's Tauri resource
/// directory. All three ddc_onset artifacts live under `resources/models/`.
fn resource_model_path(app_handle: &tauri::AppHandle, filename: &str) -> Result<PathBuf, String> {
    Ok(app_handle
        .path()
        .resource_dir()
        .map_err(|e| format!("Cannot resolve resource dir: {}", e))?
        .join("models")
        .join(filename))
}

/// Detect musically-meaningful onsets using the ddc_onset placement CNN.
///
/// Full pipeline: decode audio → 3 log-mel spectrograms with ddc_onset's
/// zero-phase windowing → per-bin normalization → ddc_onset CNN → silence
/// gate → OnsetBundle.
///
/// The model is loaded lazily on first call (~200 ms) and cached for the
/// lifetime of the app. For a 3-minute song the full pipeline takes
/// ~2 seconds on CPU (mel preprocessing dominates; inference is ~60 ms).
///
/// `music_path` must be an absolute filesystem path. For disk projects,
/// `chartStore.musicPath` is already absolute (the Rust backend
/// canonicalizes it on load). For imported charts the frontend writes the
/// blob to a temp file via `write_temp_audio` and passes that path.
#[tauri::command]
pub async fn detect_onsets_ml(
    music_path: String,
    app_handle: tauri::AppHandle,
) -> Result<OnsetBundle, String> {
    let placement_path = resource_model_path(&app_handle, "ddc_onset_placement.onnx")?;
    let extractor_path = resource_model_path(&app_handle, "ddc_onset_extractor.bin")?;
    let normalizer_path = resource_model_path(&app_handle, "ddc_onset_normalizer.bin")?;

    if !placement_path.exists() {
        return Err(format!(
            "Onset model not found at {}. Run scripts/convert_ddc_to_onnx.py first.",
            placement_path.display()
        ));
    }
    if !extractor_path.exists() {
        return Err(format!(
            "Extractor constants not found at {}. Run scripts/convert_ddc_to_onnx.py first.",
            extractor_path.display()
        ));
    }
    if !normalizer_path.exists() {
        return Err(format!(
            "Normalizer moments not found at {}. Run scripts/convert_ddc_to_onnx.py first.",
            normalizer_path.display()
        ));
    }

    // Move the entire CPU-bound pipeline to a blocking thread so we don't
    // freeze the Tauri async runtime (which handles all IPC commands).
    tauri::async_runtime::spawn_blocking(move || {
        let path = std::path::Path::new(&music_path);

        // 1. Decode audio.
        let samples = decode_audio_mono(path)?;

        // 2. Load (or re-read from cache) the extractor + normalizer constants.
        let extractor = EXTRACTOR.get_or_init(|| load_extractor(&extractor_path))
            .as_ref().map_err(|e| e.clone())?;
        let normalizer = NORMALIZER.get_or_init(|| load_normalizer(&normalizer_path))
            .as_ref().map_err(|e| e.clone())?;

        // 3. Compute 3 log-mel spectrograms in parallel. Each is independent
        //    (its own FFT planner + read-only samples slice), so rayon runs
        //    them on separate threads — wall-clock ≈ slowest single spectrogram
        //    instead of sum.
        let spectrograms: Vec<Vec<Vec<f32>>> = (0..FFT_SIZES.len())
            .into_par_iter()
            .map(|ch| {
                compute_log_mel_ddc(
                    &samples,
                    FFT_SIZES[ch],
                    &extractor.windows[ch],
                    &extractor.mels[ch],
                )
            })
            .collect::<Result<Vec<_>, String>>()?;

        // 4. Stack into [num_frames, 80, 3] and apply per-bin z-score.
        let (spec_flat, num_frames) = stack_and_normalize(
            [&spectrograms[0], &spectrograms[1], &spectrograms[2]],
            normalizer,
        );

        if num_frames == 0 {
            return Ok(OnsetBundle {
                version: ONSET_PIPELINE_VERSION,
                frames: Vec::new(),
            });
        }

        // 5. CNN inference (~60 ms on CPU for 3-min song).
        let mut probs = run_onset_model(&spec_flat, num_frames, &placement_path)?;

        // 6. Silence gate — zero probability in frames where the audio RMS
        //    is below the perceptible threshold. Same logic as the madmom
        //    pipeline (unchanged). Out-of-range indices can happen on the
        //    last 1-2 frames because num_frames is derived from the padded
        //    waveform; the bounds check handles those.
        for (i, prob) in probs.iter_mut().enumerate() {
            let start = i * HOP_SIZE;
            let end = (start + HOP_SIZE).min(samples.len());
            if start >= samples.len() || end <= start {
                *prob = 0.0;
                continue;
            }
            let mean_sq: f32 = samples[start..end].iter()
                .map(|&s| s * s)
                .sum::<f32>() / (end - start) as f32;
            if mean_sq < SILENCE_THRESHOLD {
                *prob = 0.0;
            }
        }

        // 7. Build per-frame OnsetResult. Time is derived from hop-aligned
        //    frame index: probability[i] → time i / FRAME_RATE seconds.
        let hop_seconds = HOP_SIZE as f64 / SAMPLE_RATE as f64;
        let frames: Vec<OnsetResult> = probs.iter().enumerate()
            .map(|(i, &prob)| OnsetResult {
                time: i as f64 * hop_seconds,
                probability: prob as f64,
            })
            .collect();

        Ok(OnsetBundle {
            version: ONSET_PIPELINE_VERSION,
            frames,
        })
    })
    .await
    .map_err(|e| format!("Onset detection task panicked: {}", e))?
}

/// Write audio bytes to a temporary file on disk so that `detect_onsets_ml`
/// can read it with symphonia. Called by the frontend when the chart was
/// imported (ZIP/RPE/PEC) and there is no disk file — only a blob URL.
#[tauri::command]
pub async fn write_temp_audio(
    audio_bytes: Vec<u8>,
    extension: String,
) -> Result<String, String> {
    let temp_dir = std::env::temp_dir().join("phichain-onset");

    std::fs::create_dir_all(&temp_dir)
        .map_err(|e| format!("Failed to create temp dir: {}", e))?;

    // Clean up old temp files from previous calls.
    if let Ok(entries) = std::fs::read_dir(&temp_dir) {
        for entry in entries.flatten() {
            let _ = std::fs::remove_file(entry.path());
        }
    }

    let nanos = std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap_or_default()
        .as_nanos();
    let filename = format!("onset_{}.{}", nanos, extension);
    let file_path = temp_dir.join(&filename);

    std::fs::write(&file_path, &audio_bytes)
        .map_err(|e| format!("Failed to write temp audio: {}", e))?;

    Ok(file_path.to_string_lossy().into_owned())
}
