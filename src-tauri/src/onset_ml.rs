// ── Pipeline constants (mirrored in scripts/convert_ddc_to_onnx.py) ──

/// Target sample rate — ddc_onset was trained on 44.1 kHz audio.
const SAMPLE_RATE: u32 = 44100;

/// Hop size = SAMPLE_RATE / FRAME_RATE = 441, producing 100 fps output.
const HOP_SIZE: usize = 441;

/// Number of mel frequency bands per FFT channel.
const NUM_MEL_BANDS: usize = 80;

/// ddc_onset's three FFT window sizes, in the channel order the exported
/// graph expects. **DO NOT** reorder without rebuilding the ONNX — the mel
/// matrices in ddc_onset_extractor.bin are keyed to this exact sequence.
const FFT_SIZES: [usize; 3] = [1024, 2048, 4096];

/// Log-compression floor — `ln(energy + LOG_EPS)`. Matches ddc_onset's
/// spectral.py `_LOG_EPS = 1e-16`.
const LOG_EPS: f64 = 1e-16;

/// Rubato resampler chunk size (samples per processing block).
const RESAMPLE_CHUNK: usize = 1024;

/// Silence gate threshold (mean-squared amplitude). Frames with RMS below
/// this are zeroed — the CNN can hallucinate onsets in silence because
/// silent log-mel values sit outside its training distribution.
const SILENCE_THRESHOLD: f32 = 1e-4;

/// Pipeline version carried in the IPC envelope. Bump when the output
/// shape or the meaning of `OnsetResult` changes so the frontend cache
/// invalidates cleanly across upgrades. Must match
/// `EXPECTED_ONSET_PIPELINE_VERSION` in src/utils/ipc.ts.
pub const ONSET_PIPELINE_VERSION: u32 = 2;

// ── Types ───────────────────────────────────────────────────────

/// One onset probability sample at 100 fps. Field layout is stable across
/// pipeline versions — version changes are communicated via OnsetBundle
/// and do NOT necessarily alter per-frame semantics.
#[derive(Debug, Serialize, Clone)]
pub struct OnsetResult {
    /// Time in seconds from the start of the audio file.
    pub time: f64,
    /// Onset probability 0.0-1.0 (higher = more confident).
    pub probability: f64,
}

/// Versioned envelope returned by `detect_onsets_ml`. The frontend checks
/// `version` against its compiled-in expectation and busts the salience
/// cache on mismatch — see src/hooks/useOnsetDetection.ts.
#[derive(Debug, Serialize, Clone)]
pub struct OnsetBundle {
    pub version: u32,
    pub frames: Vec<OnsetResult>,
}

/// SpectrogramExtractor constants loaded from `ddc_onset_extractor.bin`.
/// Layout (little-endian f32, generated by scripts/convert_ddc_to_onnx.py):
///
///     for fft_size in [1024, 2048, 4096]:
///         window[fft_size]              # pre-computed Hann-like window
///         mel[(fft_size/2 + 1) × 80]    # librosa mel matrix, row-major
///
/// One instance is constructed lazily per app lifetime and cached in
/// EXTRACTOR below.
struct Extractor {
    /// Per-FFT-size pre-windowed coefficients. Index matches FFT_SIZES.
    windows: [Vec<f64>; 3],
    /// Per-FFT-size dense mel matrices. Shape `[(fft_size/2+1), 80]`,
    /// stored row-major so `mel[bin][mel_band]` is a flat access.
    mels: [Vec<Vec<f64>>; 3],
}

/// Per-bin z-score moments loaded from `ddc_onset_normalizer.bin`.
///
///     mean[80 × 3]  # row-major, [mel_band][fft_channel]
///     std[80 × 3]   # same layout
struct Normalizer {
    /// `mean[mel_band][fft_channel]` — 80 × 3 = 240 f32 values.
    mean: Vec<Vec<f32>>,
    /// `std[mel_band][fft_channel]` — 80 × 3 = 240 f32 values.
    std: Vec<Vec<f32>>,
}

