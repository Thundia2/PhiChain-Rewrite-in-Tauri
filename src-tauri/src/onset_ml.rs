// 2. CONSTANT LOADING (ddc_onset_extractor.bin, ddc_onset_normalizer.bin)
// ═══════════════════════════════════════════════════════════════

/// Read a `.bin` file and interpret it as a flat Vec<f32>. The file is
/// written by convert_ddc_to_onnx.py as raw little-endian f32 bytes in a
/// documented layout; the callers below split the flat vector into the
/// per-field slices they need.
fn read_f32_le(path: &Path) -> Result<Vec<f32>, String> {
    let bytes = std::fs::read(path)
        .map_err(|e| format!("Cannot read {}: {}", path.display(), e))?;
    if bytes.len() % 4 != 0 {
        return Err(format!(
            "{} has {} bytes, not a multiple of 4 (expected f32 little-endian)",
            path.display(), bytes.len()
        ));
    }
    let mut out = Vec::with_capacity(bytes.len() / 4);
    for chunk in bytes.chunks_exact(4) {
        out.push(f32::from_le_bytes([chunk[0], chunk[1], chunk[2], chunk[3]]));
    }
    Ok(out)
}

/// Parse `ddc_onset_extractor.bin` into per-FFT-size windows + mel matrices.
///
/// File layout (matches convert_ddc_to_onnx.py::write_extractor_bin):
///
///     window_1024 (1024 f32) → mel_1024 (513 × 80 f32)
///     window_2048 (2048 f32) → mel_2048 (1025 × 80 f32)
///     window_4096 (4096 f32) → mel_4096 (2049 × 80 f32)
///
/// Windows are promoted to f64 at load time so the inner FFT loop stays
/// in f64 (matches ddc_onset's numerical regime).
fn load_extractor(path: &Path) -> Result<Extractor, String> {
    let flat = read_f32_le(path)?;
    let mut cursor = 0usize;

    // Initialize with empty Vec so we can fill by index.
    let mut windows: [Vec<f64>; 3] = [Vec::new(), Vec::new(), Vec::new()];
    let mut mels: [Vec<Vec<f64>>; 3] = [Vec::new(), Vec::new(), Vec::new()];

    for (ch, &fft_size) in FFT_SIZES.iter().enumerate() {
        let n_bins = fft_size / 2 + 1;

        // Pull window of length fft_size.
        if cursor + fft_size > flat.len() {
            return Err(format!(
                "ddc_onset_extractor.bin truncated: expected window[{}] at offset {} but only {} f32 remain",
                fft_size, cursor, flat.len() - cursor
            ));
        }
        let window_f32 = &flat[cursor..cursor + fft_size];
        windows[ch] = window_f32.iter().map(|&v| v as f64).collect();
        cursor += fft_size;

        // Pull mel matrix of shape [n_bins, 80], row-major.
        let mel_entries = n_bins * NUM_MEL_BANDS;
        if cursor + mel_entries > flat.len() {
            return Err(format!(
                "ddc_onset_extractor.bin truncated: expected mel[{}x{}] at offset {}",
                n_bins, NUM_MEL_BANDS, cursor
            ));
        }
        let mut mel = Vec::with_capacity(n_bins);
        for bin in 0..n_bins {
            let row_start = cursor + bin * NUM_MEL_BANDS;
            let row = flat[row_start..row_start + NUM_MEL_BANDS]
                .iter().map(|&v| v as f64).collect::<Vec<f64>>();
            mel.push(row);
        }
        mels[ch] = mel;
        cursor += mel_entries;
    }

    if cursor != flat.len() {
        return Err(format!(
            "ddc_onset_extractor.bin has {} trailing f32 values after expected layout",
            flat.len() - cursor
        ));
    }
    Ok(Extractor { windows, mels })
}

/// Parse `ddc_onset_normalizer.bin` into mean + std matrices of shape
/// [80, 3]. File layout: mean (80 × 3 f32, row-major), then std (same).
fn load_normalizer(path: &Path) -> Result<Normalizer, String> {
    let flat = read_f32_le(path)?;
    let expected = NUM_MEL_BANDS * FFT_SIZES.len() * 2;
    if flat.len() != expected {
        return Err(format!(
            "ddc_onset_normalizer.bin has {} f32, expected {} (= 80 × 3 × 2)",
            flat.len(), expected
        ));
    }

    let half = flat.len() / 2;
    let mut mean = Vec::with_capacity(NUM_MEL_BANDS);
    let mut std = Vec::with_capacity(NUM_MEL_BANDS);
    for band in 0..NUM_MEL_BANDS {
        let m_start = band * FFT_SIZES.len();
        mean.push(flat[m_start..m_start + FFT_SIZES.len()].to_vec());
        let s_start = half + band * FFT_SIZES.len();
        std.push(flat[s_start..s_start + FFT_SIZES.len()].to_vec());
    }
    Ok(Normalizer { mean, std })
}

// ═══════════════════════════════════════════════════════════════
// 3. LOG-MEL SPECTROGRAM (ddc_onset-compatible)
//
// Mirror of ddc_onset/spectral.py::SpectrogramExtractor.forward. Three
// things differ from the madmom-era pipeline:
//
//   1) Waveform is LEFT-PADDED by fft_size/2 zeros so frame centers align
//      with audio sample timestamps 0, HOP, 2*HOP, ...
//   2) After windowing, each frame's two halves are SWAPPED before FFT
//      ("zero-phase" windowing, inherited from essentia; see
//      https://github.com/MTG/essentia/blob/master/src/algorithms/standard/windowing.cpp#L85).
//   3) Mel projection uses a preloaded matrix (from extractor.bin) rather
//      than a triangular filterbank computed here.
// ═══════════════════════════════════════════════════════════════

/// Compute a log-mel spectrogram for one FFT size. Returns a row-major
/// `[num_frames, 80]` f32 matrix. `window` and `mel` come from
/// `Extractor` and are keyed to the FFT size — caller must pass the
/// matching pair.
fn compute_log_mel_ddc(
    samples: &[f32],
    fft_size: usize,
    window: &[f64],
    mel: &[Vec<f64>],
) -> Result<Vec<Vec<f32>>, String> {
    let half = fft_size / 2;
    let n_bins = fft_size / 2 + 1;
    debug_assert_eq!(window.len(), fft_size);
    debug_assert_eq!(mel.len(), n_bins);

    // ddc_onset left-pads the waveform with fft_size/2 zeros so the first
    // frame's center corresponds to audio sample 0. We emulate by computing
    // `padded_len = samples.len() + half` and iterating frame starts in the
    // PADDED coordinate system, reading from `samples` with a left-offset.
    let padded_len = samples.len() + half;
    // Number of frames = ceil(padded_len / HOP); the last ~fft_size/HOP
    // frames will be partial (left-padded with zeros).
    let num_frames = (padded_len + HOP_SIZE - 1) / HOP_SIZE;

    let mut planner = RealFftPlanner::<f64>::new();
    let fft = planner.plan_fft_forward(fft_size);
    let mut input_buf = vec![0.0f64; fft_size];
    let mut spectrum = fft.make_output_vec();

    let mut spectrogram = Vec::with_capacity(num_frames);

    for frame_idx in 0..num_frames {
        let padded_start = frame_idx * HOP_SIZE;

        // Fill input_buf with windowed samples from the PADDED waveform.
        // Padded index i corresponds to original-audio index (i - half).
        for i in 0..fft_size {
            let padded_idx = padded_start + i;
            let sample = if padded_idx < half {
                // In the left-pad region.
                0.0f64
            } else {
                let audio_idx = padded_idx - half;
                if audio_idx < samples.len() {
                    samples[audio_idx] as f64
                } else {
                    // Past audio end — zero-pad.
                    0.0f64
                }
            };
            input_buf[i] = sample * window[i];
        }

        // Zero-phase windowing: swap halves so the window's peak is at the
        // start of the buffer. This makes the DFT's zero-phase reference
        // coincide with the window center, matching essentia/ddc_onset.
        for i in 0..half {
            input_buf.swap(i, i + half);
        }

        // Forward FFT (real → complex, positive frequencies only).
        fft.process(&mut input_buf, &mut spectrum)
            .map_err(|e| format!("FFT at frame {} size {}: {}", frame_idx, fft_size, e))?;

        // Power spectrogram: |X[k]|² — ddc_onset uses power, not magnitude.
        // See spectral.py: `spec_r*spec_r + spec_i*spec_i` (no sqrt).
        let mut power = vec![0.0f64; n_bins];
        for (k, c) in spectrum.iter().take(n_bins).enumerate() {
            power[k] = c.re * c.re + c.im * c.im;
        }

        // Mel projection: energy[b] = sum_k mel[k][b] * power[k].
        // The mel matrix is stored row-major per-bin (n_bins × 80), so
        // we scan the n_bins × 80 multiply-adds in the natural order.
        let mut mel_frame = vec![0.0f32; NUM_MEL_BANDS];
        let mut mel_acc = vec![0.0f64; NUM_MEL_BANDS];
        for k in 0..n_bins {
            let p = power[k];
            if p == 0.0 {
                continue;
            }
            let row = &mel[k];
            for b in 0..NUM_MEL_BANDS {
                mel_acc[b] += row[b] * p;
            }
        }
        for b in 0..NUM_MEL_BANDS {
            mel_frame[b] = (mel_acc[b] + LOG_EPS).ln() as f32;
        }

        spectrogram.push(mel_frame);
    }

    Ok(spectrogram)
}

/// Stack the three per-FFT log-mel spectrograms into a `[num_frames, 80, 3]`
/// tensor in the channel order dictated by FFT_SIZES, then apply per-bin
/// z-score normalization using the loaded `Normalizer` moments.
///
/// Returns a flat Vec<f32> of length `num_frames * 80 * 3` in C order
/// (frame-major, then mel-band, then fft-channel) — the exact layout the
/// exported ONNX graph expects for its `spectrogram` input.
fn stack_and_normalize(
    specs: [&[Vec<f32>]; 3],
    normalizer: &Normalizer,
) -> (Vec<f32>, usize) {
    // Different FFT sizes produce slightly different frame counts. Align
    // to the minimum so downstream indexing is uniform.
    let num_frames = specs[0].len().min(specs[1].len()).min(specs[2].len());

    let mut out = vec![0.0f32; num_frames * NUM_MEL_BANDS * FFT_SIZES.len()];
    for t in 0..num_frames {
        for b in 0..NUM_MEL_BANDS {
            for ch in 0..FFT_SIZES.len() {
                let raw = specs[ch][t][b];
                let mean = normalizer.mean[b][ch];
                let std = normalizer.std[b][ch];
                // Guard against a divide-by-zero if a training-time bin had
                // zero variance (shouldn't happen, but defensive).
                let denom = if std.abs() < f32::EPSILON { 1.0 } else { std };
                let idx = t * NUM_MEL_BANDS * FFT_SIZES.len() + b * FFT_SIZES.len() + ch;
                out[idx] = (raw - mean) / denom;
            }
        }
    }
    (out, num_frames)
}

