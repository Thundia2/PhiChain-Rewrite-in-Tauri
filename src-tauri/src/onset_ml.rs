// ============================================================
// ML Onset Detection Pipeline — onset_ml.rs
//
// Pipeline: audio decode (symphonia) → resample to 44.1 kHz (rubato)
// → 3 log-mel spectrograms at FFT 1024/2048/4096 with ddc_onset's
// zero-phase windowing + preloaded mel matrices → per-bin z-score
// normalization → ddc_onset placement CNN (ONNX) → per-frame onset
// probability → silence gate → OnsetBundle.
//
// Recent change (Phase B of onset plan, 2026-04-20): Replaced the
// madmom CNN with Chris Donahue's `ddc_onset` placement network
// (trained on DDR chart annotations). Three user-visible impacts:
//   1) Output density drops from ~9.5/sec to a musically-clean
//      range controlled by the frontend peak-picker's density budget.
//   2) Output is wrapped in an `OnsetBundle { version, frames }`
//      envelope so the frontend can detect pipeline skew on upgrades
//      (see EXPECTED_ONSET_PIPELINE_VERSION on the TS side).
//   3) Preprocessing NO LONGER builds its own mel filterbank or
//      stacks 15-frame context; ddc_onset's exported graph does its
//      own ±7-frame padding + unfold internally. We compute
//      [num_frames, 80, 3] normalized log-mel and pass it in as a
//      single input — CHALLENGE difficulty is baked into the graph,
//      density selection happens in the frontend peak-picker.
//
// Constants and binary artifact layouts are generated by
// `scripts/convert_ddc_to_onnx.py` and documented in its header.
// ============================================================

