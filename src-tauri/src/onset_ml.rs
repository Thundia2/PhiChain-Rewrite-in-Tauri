/// Run ddc_onset's placement CNN (CHALLENGE baked in) on the normalized
/// log-mel spectrogram. Returns per-frame onset probability in [0, 1].
///
/// Unlike the madmom pipeline, we do NOT chunk — the exported graph runs
/// in ~60 ms on CPU for a full 3-minute song (14k frames), so the complexity
/// of chunking buys nothing here.
fn run_onset_model(
    spec_flat: &[f32],
    num_frames: usize,
    model_path: &Path,
) -> Result<Vec<f32>, String> {
    let session_result = ONSET_SESSION.get_or_init(|| {
        (|| -> Result<Mutex<Session>, String> {
            let builder = Session::builder()
                .map_err(|e| format!("ONNX session builder failed: {}", e))?;
            let mut builder = builder
                .with_optimization_level(GraphOptimizationLevel::Level3)
                .map_err(|e| format!("ONNX optimization level failed: {}", e))?;
            let session = builder
                .commit_from_file(model_path)
                .map_err(|e| format!(
                    "Failed to load ddc_onset CNN from {}: {} — is ddc_onset_placement.onnx present and valid?",
                    model_path.display(), e
                ))?;
            Ok(Mutex::new(session))
        })()
    });

    let session_mutex = session_result.as_ref().map_err(|e| e.clone())?;
    let mut session = session_mutex.lock()
        .map_err(|e| format!("Session lock poisoned: {}", e))?;

    // Build the [num_frames, 80, 3] tensor. We own the data via to_vec() —
    // ort takes ownership of the tensor's backing storage.
    let input_array = Array3::<f32>::from_shape_vec(
        (num_frames, NUM_MEL_BANDS, FFT_SIZES.len()),
        spec_flat.to_vec(),
    ).map_err(|e| format!("Tensor shape error: {}", e))?;

    let input_tensor = Tensor::from_array(input_array)
        .map_err(|e| format!("ONNX tensor error: {}", e))?;

    let outputs = session.run(
        ort::inputs!["spectrogram" => input_tensor]
    ).map_err(|e| format!("ONNX inference error: {}", e))?;

    let (_shape, prob_data) = outputs["onset_probability"]
        .try_extract_tensor::<f32>()
        .map_err(|e| format!("ONNX output error: {}", e))?;

    Ok(prob_data.to_vec())
}

